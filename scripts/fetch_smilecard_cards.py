"""Rebuild smilecard-site/cards-data.js: every card in the galleries of the original smilecard.org (Wix) site.

Run from the repo root:
    .\\.venv\\Scripts\\python.exe scripts\\fetch_smilecard_cards.py

It makes the same public requests a visitor's browser makes when pressing "Load More" in a gallery
(a visitor token from /_api/v1/access-tokens, then the gallery pages 100 items at a time). It saves only
the image ids, in gallery order. File names are not saved: many contain volunteers' names.
The cards stay hosted by Wix (static.wixstatic.com); this script does not download them.
"""
import json
import re
import time
import urllib.request
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "smilecard-site" / "cards-data.js"
SITE = "https://www.smilecard.org"
PRO_GALLERY_APP = "14271d6f-ba62-d045-549b-ab972ae1f70e"

# key: (label, gallery id on smilecard.org, page it is on there)
SETS = {
    "recent": ("Recent Cards", "43d5f6e3-eb02-442b-9fbe-c9a3bc0586ec", "/new-cards"),
    "all": ("All Cards", "09a3e96c-372b-4159-80ac-1a3f3817155e", "/all-cards"),
    "handmade": ("Handmade", "11c350ee-afd2-48db-98a7-6a1b955ef57a", "/card-gallery"),
    "digital": ("Digital", "752b5b9e-723b-4f4e-9a50-f1e9cee636cc", "/card-gallery"),
    "nature": ("Nature & Floral", "ed6cdcc5-ab77-44ae-a1f7-27b6fee08635", "/card-gallery"),
    "holiday": ("Holiday", "33344140-a794-4ff1-924f-0ade88d59f38", "/card-gallery"),
    "letters": ("Letters", "38e8c893-06c2-4149-93fd-ef4cee9cfc9d", "/card-gallery"),
    "religious": ("Religious", "67135163-4f96-4ef2-918c-e1389f2d9ffe", "/card-gallery"),
    "jacobs-heart": ("Jacob's Heart", "d7c80cb6-6a69-4f7e-ac26-c8275cb0a99b", "/trinity-school"),
}
ID = re.compile(r"/media/([0-9a-f]{6}_[0-9a-f]{32}~mv2\.[a-z]+)$")


def get_json(url, headers=None):
    request = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0", **(headers or {})})
    with urllib.request.urlopen(request, timeout=60) as response:
        return json.loads(response.read().decode("utf-8"))


def fetch_set(gallery_id, token):
    ids, offset, total = [], 0, None
    while total is None or offset < total:
        gallery = get_json(f"{SITE}/pro-gallery-webapp/v1/galleries/{gallery_id}?offset={offset}&limit=100",
                           {"Authorization": token})["gallery"]
        total, batch = gallery["totalItemsCount"], gallery.get("items") or []
        if not batch:
            break
        for item in batch:
            match = ID.search(item.get("mediaUrl", ""))
            if not match:
                raise SystemExit(f"unexpected image address in gallery {gallery_id}: {item.get('mediaUrl')!r}")
            ids.append(match.group(1))
        offset += len(batch)
        time.sleep(0.2)
    if len(ids) != total:
        raise SystemExit(f"gallery {gallery_id}: expected {total} cards, got {len(ids)}")
    return ids


def main():
    token = get_json(f"{SITE}/_api/v1/access-tokens")["apps"][PRO_GALLERY_APP]["instance"]
    sets = {}
    for key, (label, gallery_id, page) in SETS.items():
        sets[key] = fetch_set(gallery_id, token)
        print(f"{label:16} {len(sets[key]):5} cards (from {SITE}{page})")
    labels = {key: label for key, (label, _, _) in SETS.items()}
    lines = [
        "// Every card in the galleries of the original smilecard.org site, in the same order.",
        "// Generated by scripts/fetch_smilecard_cards.py - run it again instead of editing this file.",
        "// The images are hosted by Wix: https://static.wixstatic.com/media/<id>",
        f"export const labels = {json.dumps(labels, ensure_ascii=False)};",
        "export const sets = {",
        *[f"  {json.dumps(key)}: {json.dumps(ids, separators=(',', ':'))}," for key, ids in sets.items()],
        "};",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    unique = len({i for ids in sets.values() for i in ids})
    print(f"wrote {OUT.relative_to(REPO)}: {sum(map(len, sets.values()))} entries, {unique} different cards")


if __name__ == "__main__":
    main()
